package oops;



public class leaningOOPs {
	public static void main(String[] args) {
		// constructor chaining
		class3 obj1 = new class3();
		
	}
 }
class class1 
{
	public class1()
	{
		System.out.println("this is class 1 constructor");
	}
}
class class2 extends class1
{
	public class2()
	{
		System.out.println("this is class 2 constructor");
	}
}
class class3 extends class2
{
	public class3()
	{
		System.out.println("this is class 3 constructor");
	}
}
















